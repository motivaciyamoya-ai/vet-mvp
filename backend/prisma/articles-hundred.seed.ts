function noteNum(i: number): number {
  return Math.floor(i / STEMS.length) + 1;
}

const BODY_TRUNC_SUFFIX = `\n\n[Фрагмент текста усечён до лимита серии VetConnect (${BODY_MAX} симв.); полная версия ведётся в локальной ЭМК.]`;

/** После подстановки markdown-ссылок тело может вырасти — удерживаем в пределах BODY_MAX. */
function clampArticleBodyLen(body: string): string {
  if (body.length <= BODY_MAX) return body;
  const budget = BODY_MAX - BODY_TRUNC_SUFFIX.length;
  let head = body.slice(0, Math.max(budget - 1, BODY_MIN)).trimEnd();
  let cut = head.lastIndexOf('\n\n');
  if (cut < BODY_MIN) cut = BODY_MIN;
  head = head.slice(0, cut).trimEnd();
  let out = head + BODY_TRUNC_SUFFIX;
  if (out.length > BODY_MAX) out = out.slice(0, BODY_MAX).trimEnd();
  return out;
}

